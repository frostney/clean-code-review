import { SpeedInsights } from '@vercel/speed-insights/next';
import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import type { ReactNode } from 'react';

import { ThemeToggle } from '@/app/_components/ThemeToggle';
import { SITE } from '@/lib/site';
import { THEME_SCRIPT } from '@/lib/theme';
import './globals.css';

const sans = Geist({
  display: 'swap',
  subsets: ['latin'],
  variable: '--font-sans',
  weight: 'variable',
});

const mono = Geist_Mono({
  display: 'swap',
  subsets: ['latin'],
  variable: '--font-mono',
  weight: 'variable',
});

/**
 * What this page tells a crawler, a link preview and an answer engine.
 *
 * `metadataBase` is what makes every relative URL below absolute, including
 * the Open Graph image generated by `opengraph-image.tsx`. The title carries a
 * template so that a second route — a permalinked review, say — reads as part
 * of the same product without repeating its name.
 */
export const metadata: Metadata = {
  alternates: { canonical: '/' },
  applicationName: SITE.name,
  authors: [{ name: 'frostney', url: 'https://github.com/frostney' }],
  category: 'developer tools',
  creator: 'frostney',
  description: SITE.description,
  keywords: [
    'clean code',
    'code review',
    'pull request review',
    'AI code review',
    'code smells',
    'Clean Code checklist',
    'GitHub pull request',
    'diff review',
    'Jev',
    'TypeSafe',
    'eve agent',
  ],
  metadataBase: new URL(SITE.url),
  openGraph: {
    description: SITE.description,
    locale: 'en_US',
    siteName: SITE.name,
    title: SITE.name,
    type: 'website',
    url: SITE.url,
  },
  robots: { follow: true, index: true },
  title: {
    default: SITE.name,
    template: `%s · ${SITE.name}`,
  },
  twitter: {
    card: 'summary_large_image',
    description: SITE.description,
    title: SITE.name,
  },
};

export default function RootLayout({
  children,
}: {
  readonly children: ReactNode;
}) {
  return (
    <html
      className={`${sans.variable} ${mono.variable}`}
      lang="en"
      suppressHydrationWarning={true}
    >
      <body className="font-sans antialiased">
        {/* The theme, before the first pixel. It is the first thing in the
            document body so that the attribute the palette keys off is already
            on `<html>` when the browser paints, rather than one render later —
            a page that flashes white on the way to black has told the reader it
            forgot which one they asked for. */}
        <script
          // biome-ignore lint/security/noDangerouslySetInnerHtml: an inline script is the only thing that runs before paint, and every byte of it is written in lib/theme.ts
          dangerouslySetInnerHTML={{ __html: THEME_SCRIPT }}
        />
        {/* The theme switch, once for every page, in the top right corner of
            the page's own column. It is laid over the page rather than given a
            row, because on every page but one that corner is empty: the
            landing duck is centred, the questions and the privacy page open on
            the left, and from `lg` up the code view's field is four fifths
            wide. The one exception is the code view below `lg`, where the
            field takes the whole line, and `Shell` makes room above it there
            rather than let this take width from the address.
            It comes first in the document, so it is the first stop on the way
            down the page with Tab, which is where it is on screen. The strip is
            click-through; only the button takes the pointer. */}
        <div className="pointer-events-none absolute inset-x-0 top-0 z-10">
          <div className="mx-auto flex max-w-[1280px] justify-end px-4 lg:pt-5">
            <div className="-mr-3 pointer-events-auto flex h-10 items-center lg:-mr-2.5 lg:h-9">
              <ThemeToggle />
            </div>
          </div>
        </div>
        {children}
        {/* Page-speed measurement, and nothing else: what it sends and where
            is on /privacy. It renders nothing, and its script is added from
            the browser once the page has hydrated. */}
        <SpeedInsights />
      </body>
    </html>
  );
}
